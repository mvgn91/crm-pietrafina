import assert from 'node:assert/strict';
import { getDemoProspects } from '../../public/preview.js';
import { dormantProspects, computeEligibility, matchesSearch } from '../../public/reactivacion-model.js';
import { recordAction } from '../../public/phase2-actions.js';
const now=new Date(2026,10,17,12),rows=getDemoProspects(now),before=JSON.stringify(rows),dormant=dormantProspects(rows,now);
assert.equal(rows.length,103);assert.equal(dormant.length,100);
for(const [segment,count] of Object.entries({interesado:3,vencido:7,prospeccion:85,nunca:5}))assert.equal(dormant.filter(p=>p.segment===segment).length,count);
assert.equal(dormant.filter(p=>!p.nextFollowUpDate && p.segment!=='nunca').length,88);
assert.ok(dormant.filter(p=>p.segment==='nunca').every(p=>p.requiresResearch));
assert.equal(JSON.stringify(rows),before);
let p=rows[0];p=recordAction(p,{note:'No respondió',now});
assert.ok(computeEligibility(p,now).eligible,'note alone never removes a row');
const changed=recordAction(p,{note:'Hay interés',newStatus:'Interesado',now});
assert.ok(!computeEligibility(changed,now).eligible);
const future=recordAction(p,{note:'Se agenda',followUpDate:'2026-11-20',now});
assert.ok(!computeEligibility(future,now).eligible);
assert.ok(computeEligibility({...p,nextFollowUpDate:'2026-11-17'},now).eligible,'today stays due');
assert.ok(matchesSearch({businessName:'DISEÑO'},'diseno'));
assert.throws(()=>recordAction(p,{note:''}),/nota/);
console.log('reactivacion: PASS 103 total, 100 dormant, 88 no date + 7 overdue + 5 research, note/status/future-date rules');
