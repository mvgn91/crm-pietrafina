import assert from 'node:assert/strict';
import { modalDraft, renderDetailCadence } from '../../public/modal-whatsapp.js';
import { createDraftStore } from '../../public/draft-store.js';
const values=new Map(),storage={getItem:k=>values.get(k),setItem:(k,v)=>values.set(k,v)};
const p={id:'1',status:'Interesado'},store=createDraftStore(storage,'u');
store.save({...p,sequence:{completedTouches:1,nextAt:'2026-11-20'}});
assert.equal(modalDraft(p,'u',storage).prospect.sequence.completedTouches,1);
store.importRows([{id:'2',status:'Rechazado'}]);assert.equal(modalDraft(p,'u',storage).prospect.id,'1','never use first imported row for a different prospect');
const nodes=new Map(),parent={append(el){nodes.set(el.id,el);}};nodes.set('detail-status',{parentNode:parent});
globalThis.document={getElementById:id=>nodes.get(id),createElement:()=>({})};
renderDetailCadence({...p,sequence:{completedTouches:1,nextAt:'2026-11-20'}});
assert.ok(nodes.get('detail-cadence').textContent.includes('Toque 2/3'));
renderDetailCadence({...p,sequence:{completed:true},nextFollowUpDate:'2026-12-24'});
assert.ok(nodes.get('detail-cadence').textContent.includes('Cadencia cerrada'));
assert.equal(nodes.size,2,'badge reused instead of duplicated');
delete globalThis.document;
console.log('modal: PASS draft overlay, correct ID after import, current cadence badge, no duplicate badge');
// Actual modal composition reads the same editable template package as the new page.
const { renderModalMessage }=await import('../../public/modal-whatsapp.js');
store.setTemplates({plantillas:{recontacto:{titulo:'Recontacto',texto:'Hola, plantilla editable.'},interesado:{titulo:'Interesado',texto:'Hola, texto para interesados.'}}});
globalThis.localStorage=storage;
globalThis.Option=class {constructor(text,value){this.text=text;this.value=value;}};
globalThis.document={getElementById:id=>nodes.get(id),createElement:()=>({append(el){nodes.set(el.id,el);},replaceChildren(...options){this.options=options;this.value=options[0]?.value || '';}})};
const textarea={value:'',parentNode:{insertBefore(){}}};
await renderModalMessage({prospect:p,uid:'u',textarea});
assert.equal(textarea.value,'Hola, texto para interesados.');
nodes.get('modal-template').value='recontacto';nodes.get('modal-template').onchange();
assert.equal(textarea.value,'Hola, plantilla editable.');
delete globalThis.document;delete globalThis.localStorage;delete globalThis.Option;
console.log('modal templates: PASS shared local edits and scenario selector');
